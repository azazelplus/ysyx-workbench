/***************************************************************************************
 * 键盘输入设备 IOE 实现
 * 
 * 【设备功能】
 * 通过 AM 库读取键盘输入。当用户按下或释放键盘按键时，
 * NEMU 会更新键盘设备的内部寄存器。
 * 
 * 【AM API】
 * io_read(AM_INPUT_KEYBRD, &kbd)  读取键盘事件
 * 
 * 【输出数据结构】 AM_INPUT_KEYBRD_T
 * - keydown: 1 表示按键按下，0 表示释放
 * - keycode: 按下/释放的键对应的键码值
 * 
 * 【NEMU 键盘设备】
 * - 地址: KBD_ADDR (0xa0000060)
 * - 格式: keycode | (keydown ? 0x8000 : 0)
 * - 当无按键时返回 AM_KEY_NONE (0)
 ***************************************************************************************/

#include <am.h>
#include <nemu.h>

#define KEYDOWN_MASK 0x8000

/***************************************************************************************
 * __am_input_config - 读取键盘输入设备配置
 * 
 * 【参数说明】
 * @param cfg: 接收配置信息的结构体指针
 *             - present: 是否存在输入设备
 * 
 * 【说明】
 * 返回输入设备的存在状态。在 NEMU 平台中，通常认为输入设备（键盘）是存在的。
 ***************************************************************************************/
void __am_input_config(AM_INPUT_CONFIG_T *cfg) {
  cfg->present = true;
}

/***************************************************************************************
 * __am_input_keybrd - 读取键盘按键事件
 * 
 * 【参数说明】
 * @param kbd: 接收键盘事件的结构体指针
 *             - keydown: 按键是否按下 (true: 按下, false: 释放)
 *             - keycode: 按键的键码 (对应 AM 定义的键码值)
 * 
 * 【说明】
 * 从 NEMU 的 KBD_ADDR 寄存器读取键码。
 * bit[15] 为按键状态 (1=down, 0=up)，bit[14:0] 为键码。
 * 读取后将解析结果填入 kbd 结构体。
 ***************************************************************************************/
void __am_input_keybrd(AM_INPUT_KEYBRD_T *kbd) {
  // 从 NEMU 键盘设备寄存器读取键码
  uint32_t kbdata = inl(KBD_ADDR);
  // 解析键码：高位是 keydown 标志，低位是实际的 keycode
  kbd->keydown = (kbdata & KEYDOWN_MASK) ? true : false;
  kbd->keycode = kbdata & ~KEYDOWN_MASK;
}
